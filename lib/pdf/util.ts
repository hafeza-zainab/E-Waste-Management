import { PDFDocument, PDFFont, PDFPage, rgb, StandardFonts } from "pdf-lib";
import QRCode from "qrcode";

export const A4: [number, number] = [595.28, 841.89];
export const TEAL = rgb(0.06, 0.46, 0.43);
export const GREY = rgb(0.4, 0.4, 0.4);
export const INK = rgb(0.1, 0.1, 0.1);

/**
 * User text -> something the standard Helvetica font (WinAnsi) can encode. pdf-lib escapes PDF string
 * syntax itself; this strips control characters, replaces anything unencodable with "?" and clamps length,
 * so hostile or exotic input can neither throw nor smuggle layout-breaking characters.
 */
export function pdfSafe(input: string, max = 200): string {
  return Array.from(input.normalize("NFC"))
    .map((ch) => {
      const c = ch.codePointAt(0)!;
      if (c < 0x20 || c === 0x7f) return " ";
      if ((c >= 0x20 && c <= 0x7e) || (c >= 0xa0 && c <= 0xff)) return ch;
      return "?";
    })
    .join("")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, max);
}

/** Greedy word wrap by measured width. Overlong words are hard-split. */
export function wrap(text: string, font: PDFFont, size: number, maxWidth: number): string[] {
  const lines: string[] = [];
  let line = "";
  for (const word of text.split(" ")) {
    let w = word;
    while (font.widthOfTextAtSize(w, size) > maxWidth) {
      let cut = w.length - 1;
      while (cut > 1 && font.widthOfTextAtSize(w.slice(0, cut), size) > maxWidth) cut--;
      if (line) { lines.push(line); line = ""; }
      lines.push(w.slice(0, cut));
      w = w.slice(cut);
    }
    const test = line ? `${line} ${w}` : w;
    if (font.widthOfTextAtSize(test, size) <= maxWidth) line = test;
    else { lines.push(line); line = w; }
  }
  if (line) lines.push(line);
  return lines;
}

export async function newDoc(title: string) {
  const doc = await PDFDocument.create();
  doc.setTitle(pdfSafe(title, 100));
  doc.setProducer("ReLoop (sandbox demo)");
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  return { doc, font, bold };
}

/** Draws a QR code as vector squares. */
export function drawQr(page: PDFPage, text: string, x: number, y: number, size: number) {
  const qr = QRCode.create(text, { errorCorrectionLevel: "M" });
  const n = qr.modules.size;
  const cell = size / n;
  for (let r = 0; r < n; r++)
    for (let c = 0; c < n; c++)
      if (qr.modules.data[r * n + c]) page.drawRectangle({ x: x + c * cell, y: y + size - (r + 1) * cell, width: cell + 0.2, height: cell + 0.2, color: INK });
}

export const DEMO_FOOTER = "SANDBOX / DEMO DOCUMENT. Generated by ReLoop for a hackathon demo. Payments use the PayPal sandbox; no real money moved.";

export function footer(page: PDFPage, font: PDFFont, extra?: string) {
  const lines = wrap(pdfSafe(extra ? `${DEMO_FOOTER} ${extra}` : DEMO_FOOTER, 400), font, 8, A4[0] - 100);
  lines.forEach((l, i) => page.drawText(l, { x: 50, y: 40 - i * 10, size: 8, font, color: GREY }));
}
